'use strict';
const { chromium } = require('playwright');
const BASE = 'https://beelo.beelestial.co.uk';
const sleep = ms => new Promise(r => setTimeout(r, ms));
let fails = 0;
const ok = (l, c, x) => { console.log((c ? '  OK   ' : '  FAIL ') + l + (!c && x ? ' — ' + JSON.stringify(x) : '')); if (!c) fails++; };
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  await ctx.addInitScript(() => { if (sessionStorage.getItem('lmt') !== '1') { localStorage.clear(); sessionStorage.clear(); } localStorage.setItem('advisoros_enc_test', '1'); localStorage.setItem('advisoros_config', JSON.stringify({ onboardingComplete: true })); sessionStorage.setItem('lmt', '1'); });
  const page = await ctx.newPage();
  const errs = [];
  page.on('console', m => { if (m.type() === 'error' && !/frame-ancestors|Failed to load|Leaflet/.test(m.text())) errs.push(m.text().slice(0, 100)); });
  await page.goto(BASE + '/');
  await page.waitForFunction(() => typeof App !== 'undefined' && App.currentHash === 'today', null, { timeout: 45000 });
  await sleep(1200);
  await page.evaluate(() => { try { App.closeModal({ all: true, silent: true }); } catch (e) {} }).catch(() => {});
  await page.evaluate(() => App.navigate('money'));
  await sleep(900);
  await page.evaluate(() => { const b = document.querySelector('[data-action="MoneyFeature.openExpenseModal"]'); if (b) b.click(); });
  await sleep(600);
  await page.locator('#expense-amount').click();
  await page.keyboard.type('7.99');
  await sleep(300);
  const st = await page.evaluate(() => ({ open: !!document.querySelector('.modal-overlay.active'), v: document.getElementById('expense-amount') ? document.getElementById('expense-amount').value : 'GONE' }));
  ok('live: typing in the expense modal keeps it open (value ' + st.v + ')', st.open && st.v === '7.99', st);
  ok('live: zero console errors while typing', errs.length === 0, errs);
  await browser.close();
  console.log(fails === 0 ? '\nLIVE MODAL TYPING CHECK PASSED' : '\nLIVE MODAL TYPING CHECK FAILED');
  process.exit(fails === 0 ? 0 : 1);
})().catch(e => { console.error('LIVE MT FAILED:', e.message.slice(0, 160)); process.exit(1); });
