import assert from 'node:assert/strict';
import { VisitReview, validateAudio, validateSummary, MAX_AUDIO_BYTES } from '../pilot/visit-review/contract.mjs';
const audio = { name: 'SYNTHETIC.wav', type: 'audio/wav', size: 100 };
const session = new VisitReview();
assert.throws(() => session.prepare('hello'));
for (const file of [null, { ...audio, size: 0 }, { ...audio, size: MAX_AUDIO_BYTES + 1 }, { ...audio, type: 'text/html' }]) assert.throws(() => validateAudio(file));
session.select(audio);
assert.throws(() => session.approve({}, true));
const draft = session.prepare('Requirement: Blackout\nObservation: Width 1200 mm\nPromise: Send samples\nMissing: Drop\nNext: Confirm fabric\n<script>untrusted</script>');
assert.equal(draft.mode, 'local-mock');
assert.equal(draft.summary.requirements, 'Blackout');
assert.equal(draft.summary.observations, 'Width 1200 mm\n<script>untrusted</script>');
assert.equal(draft.summary.promises, 'Send samples');
assert.equal(draft.summary.missing, 'Drop');
assert.equal(draft.summary.next, 'Confirm fabric');
assert.throws(() => session.approve(draft.summary, false));
assert.throws(() => validateSummary({ ...draft.summary, extra: 'unexpected' }));
assert.throws(() => validateSummary({ ...draft.summary, next: [] }));
const approved = session.approve({ ...draft.summary, next: 'Adviser edited next action' }, true);
assert.equal(approved.summary.next, 'Adviser edited next action');
assert.equal(approved.approval.status, 'approved');
assert(!('audio' in approved));
assert.throws(() => session.approve(draft.summary, true));
session.select(audio); session.prepare('Observation: example');
assert.throws(() => session.select({ ...audio, type: 'text/plain' }));
assert.equal(session.state, 'empty'); assert.equal(session.draft, null);
session.select(audio); session.prepare('Observation: example');
assert.throws(() => session.prepare(''));
assert.throws(() => session.approve(draft.summary, true));
session.discard(); assert.equal(session.file, null);
console.log('PASS visit review: validation, grouping, approval, replacement, discard; no cloud dependencies');
